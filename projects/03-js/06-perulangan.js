// For Loop
console.log("For Loop:");
for (let i = 0; i < 5; i++) {
    console.log("Iterasi ke-" + i);
}

// While Loop
console.log("\nWhile Loop:");
let j = 0;
while (j < 5) {
    console.log("While ke-" + j);
    j++;
}

// For...of (untuk array)
console.log("\nFor...of Loop:");
let buah = ["Apel", "Jeruk", "Mangga"];
for (let item of buah) {
    console.log(item);
}
