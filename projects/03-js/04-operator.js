// Aritmatika
console.log("Aritmatika:");
console.log(5 + 3);   // 8  (tambah)
console.log(5 - 3);   // 2  (kurang)
console.log(5 * 3);   // 15 (kali)
console.log(5 / 3);   // 1.67 (bagi)
console.log(5 % 3);   // 2  (sisa bagi / modulus)

// Perbandingan
console.log("\nPerbandingan:");
console.log(5 == "5");    // true  (sama nilai, beda tipe OK)
console.log(5 === "5");   // false (sama nilai DAN tipe — GUNAKAN INI)
console.log(5 !== 3);     // true  (tidak sama)
console.log(5 > 3);       // true
console.log(5 <= 3);      // false

// Logika
console.log("\nLogika:");
console.log(true && false);   // false (DAN)
console.log(true || false);   // true  (ATAU)
console.log(!true);           // false (TIDAK)
